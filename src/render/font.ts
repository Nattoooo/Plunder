interface Glyph {
  x: number;
  w: number;
}

const GH = 7;
const glyphs: Record<string, Glyph> = {};
let atlasW = 0;
for (const ch in G) {
  const w = G[ch].split('|')[0].length;
  glyphs[ch] = { x: atlasW, w };
  atlasW += w + 2;
}

const atlases = new Map<number, HTMLCanvasElement>();

function atlas(color: number): HTMLCanvasElement {
  let a = atlases.get(color);
  if (a) return a;
  a = document.createElement('canvas');
  a.width = atlasW;
  a.height = GH + 2;
  const ctx = a.getContext('2d')!;
  const hex = '#' + color.toString(16).padStart(6, '0');
  for (const pass of [0, 1]) {
    ctx.fillStyle = pass ? hex : '#140e0a';
    for (const ch in G) {
      const rows = G[ch].split('|');
      const gx = glyphs[ch].x + 1;
      for (let y = 0; y < GH; y++) for (let x = 0; x < rows[y].length; x++) {
        if (rows[y][x] !== '#') continue;
        if (pass) ctx.fillRect(gx + x, 1 + y, 1, 1);
        else ctx.fillRect(gx + x - 1, y, 3, 3);
      }
    }
  }
  atlases.set(color, a);
  return a;
}

function pxSize(k: number): number {
  return Math.max(1, Math.round(k * 0.75)) / k;
}

function measure(s: string): number {
  let w = 0;
  for (const ch of s) w += (glyphs[ch] ?? glyphs['?']).w + 1;
  return Math.max(0, w - 1);
}

export function textWidth(s: string, k = 1): number {
  return measure(s.toUpperCase()) * pxSize(k);
}

export function drawText(ctx: CanvasRenderingContext2D, s: string, x: number, y: number, color = 0xffffff, center = false, k = 1): void {
  const a = atlas(color);
  const str = s.toUpperCase();
  const p = pxSize(k);
  let px = Math.round((center ? x - (measure(str) * p) / 2 : x) * k) / k;
  const py = Math.round((y - GH * p * 0.5) * k) / k;
  for (const ch of str) {
    const g = glyphs[ch] ?? glyphs['?'];
    if (ch !== ' ') ctx.drawImage(a, g.x, 0, g.w + 2, GH + 2, px - p, py - p, (g.w + 2) * p, (GH + 2) * p);
    px += (g.w + 1) * p;
  }
}
